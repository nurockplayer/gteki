def build_shells(dz, tabby):
    import bmesh
    import bpy
    from mathutils import Matrix, Vector

    bm = bmesh.new()
    colours = []   # (vertex, rgb)
    groups = []    # (vertices, group name)

    def shell_add(points, faces, colour, group):
        verts = [bm.verts.new(point) for point in points]
        colours.extend((v, colour) for v in verts)
        groups.append((verts, group))
        for face in faces:
            bm.faces.new([verts[i] for i in face])
        return verts

    def ear(s):
        base = Vector((s * 0.026, 0.178, 0.264 + dz))
        rot = Matrix.Rotation(math.radians(18.0 * s), 3, 'Y') @ Matrix.Rotation(math.radians(-8.0), 3, 'X')
        w, h = 0.015, 0.030
        pts = [base + rot @ Vector((x, -0.006 - y, z))
               for x, y, z in [(-w, 0, -0.008), (w, 0, -0.008), (0, 0, h),
                               (-w, 0.012, -0.010), (w, 0.012, -0.010), (0, 0.002, h)]]
        shell_add([tuple(p) for p in pts], [(0, 1, 2), (3, 5, 4), (0, 3, 4, 1), (1, 4, 5, 2), (2, 5, 3, 0)],
                  BACK_L, f"ear_{'L' if s < 0 else 'R'}")
        inner = [base + rot @ Vector((x, 0.0012, z)) for x, z in [(-w * 0.62, -0.002), (w * 0.62, -0.002), (0, h * 0.78)]]
        shell_add([tuple(p) for p in inner], [(0, 1, 2)], INNER_EAR_L, f"ear_{'L' if s < 0 else 'R'}")

    def ell(centre, direction, radii, colour, group, segments=8, rings=6, slant=0.0):
        tmp = bmesh.new()
        bmesh.ops.create_uvsphere(tmp, u_segments=segments, v_segments=rings, radius=1.0)
        rot = Vector(direction).normalized().to_track_quat('X', 'Z').to_matrix().to_4x4() @ Matrix.Rotation(slant, 4, 'X')
        bmesh.ops.transform(tmp, matrix=Matrix.Translation(centre) @ rot @ Matrix.Diagonal((*radii, 1)),
                            verts=tmp.verts)
        mapping = {}
        for v in tmp.verts:
            nv = bm.verts.new(v.co.copy())
            mapping[v] = nv
            colours.append((nv, colour))
        for face in tmp.faces:
            bm.faces.new([mapping[v] for v in face.verts])
        groups.append((list(mapping.values()), group))
        tmp.free()

    for s in (-1, 1):
        ear(s)
        n = Vector((s * 0.55, 0.80, 0.12)).normalized()
        c = Vector((s * 0.0220, 0.2125, 0.2475 + dz))
        ell(c, n, (0.0035, 0.0088, 0.0066), EYE_L, "head", slant=math.radians(16.0) * s)
        ell(c + n * 0.0030, n, (0.0014, 0.0021, 0.0060), PUPIL_L, "head", segments=6, rings=4)
    ell(Vector((0.0, 0.2315, 0.2335 + dz)), (0, 1, 0.3), (0.0035, 0.0060, 0.0040), NOSE_L, "head", segments=6, rings=4)

    bm.verts.index_update()
    indices = {}
    for verts, group in groups:
        indices.setdefault(group, []).extend(v.index for v in verts)
    mesh = bpy.data.meshes.new("cat_shells")
    bm.to_mesh(mesh)
    bm.free()
    for poly in mesh.polygons:
        poly.use_smooth = False
    obj = bpy.data.objects.new("cat_shells", mesh)
    bpy.context.scene.collection.objects.link(obj)
    attr = mesh.color_attributes.new(name="Col", type='FLOAT_COLOR', domain='POINT')
    for i, (_v, colour) in enumerate(colours):
        attr.data[i].color = (*colour, 1.0)
    _set_active_colour(mesh, attr)
    for group, ids in indices.items():
        vg = obj.vertex_groups.new(name=group)
        vg.add(ids, 1.0, 'REPLACE')
    return obj


