class Checker:
    def __init__(self):
        self.failures = []

    def check(self, ok, message):
        print(("PASS " if ok else "FAIL ") + message)
        if not ok:
            self.failures.append(message)
        return ok


def mesh_triangles(mesh):
    mesh.calc_loop_triangles()
    return len(mesh.loop_triangles)


def body_components(mesh):
    parent = list(range(len(mesh.vertices)))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[rb] = ra

    for edge in mesh.edges:
        union(edge.vertices[0], edge.vertices[1])
    return len({find(i) for i in range(len(mesh.vertices))})


def component_bounds(mesh):
    parent = list(range(len(mesh.vertices)))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    for edge in mesh.edges:
        ra, rb = find(edge.vertices[0]), find(edge.vertices[1])
        if ra != rb:
            parent[rb] = ra
    groups = {}
    for i, v in enumerate(mesh.vertices):
        groups.setdefault(find(i), []).append(v.co)
    out = []
    for coords in groups.values():
        low = tuple(round(min(c[i] for c in coords), 3) for i in range(3))
        high = tuple(round(max(c[i] for c in coords), 3) for i in range(3))
        out.append((low, high, len(coords)))
    return out


def non_manifold_edges(mesh):
    counts = {}
    for poly in mesh.polygons:
        n = len(poly.vertices)
        for i in range(n):
            a, b = poly.vertices[i], poly.vertices[(i + 1) % n]
            key = (min(a, b), max(a, b))
            counts[key] = counts.get(key, 0) + 1
    return [key for key, count in counts.items() if count != 2]


def section_loops(mesh, height, tolerance=1e-5):
    """Closed loops of the horizontal slice at `height`, as sets of intersection points."""
    segments = []
    verts = [v.co for v in mesh.vertices]
    for poly in mesh.polygons:
        idx = list(poly.vertices)
        crossings = []
        for i in range(len(idx)):
            a, b = verts[idx[i]], verts[idx[(i + 1) % len(idx)]]
            da, db = a.z - height, b.z - height
            if (da < 0.0 <= db) or (db < 0.0 <= da):
                crossings.append(a.lerp(b, da / (da - db)))
        if len(crossings) == 2:
            segments.append((crossings[0], crossings[1]))
    if not segments:
        return []
    def key(point):
        return (round(point.x / tolerance), round(point.y / tolerance), round(point.z / tolerance))
    graph = {}
    for a, b in segments:
        graph.setdefault(key(a), []).append(key(b))
        graph.setdefault(key(b), []).append(key(a))
    seen, loops = set(), []
    for start in graph:
        if start in seen:
            continue
        stack, component = [start], set()
        while stack:
            node = stack.pop()
            if node in component:
                continue
            component.add(node)
            stack.extend(n for n in graph[node] if n not in component)
        seen |= component
        loops.append(component)
    return loops


def rigid_paws(body):
    """Make each paw's geometry rigid to its own bone: the floor contact is then exactly the bone's."""
    wanted = {}
    for leg in LEGS:
        front = leg["front"]
        name = f"{PAW_GROUP[front]}_{'L' if leg['side'] < 0 else 'R'}"
        x0 = leg["side"] * LEG_X[front]
        wanted[name] = {v.index for v in body.data.vertices
                        if v.co.z <= ANKLE_Z[front] + 0.004
                        and abs(v.co.x - x0) <= 0.030 and abs(v.co.y - REST_Y[front]) <= 0.055}
    for name in list(wanted):
        group = body.vertex_groups.get(name)
        if group is None:
            wanted.pop(name, None)
            continue
        for other in body.vertex_groups:
            if other.name != name:
                other.remove([i for i in wanted[name]])
        group.add(sorted(wanted[name]), 1.0, 'REPLACE')


def calibrate_paws(arm, body, targets, poles, world, groups):
    """Lower each stance target so every paw sole touches y = 0 in the rest pose."""
    import bpy
    add_leg_rig(arm, targets, poles, world)
    for leg in LEGS:
        targets[leg["key"]].location = ik_targets_for(leg, REST_Y[leg["front"]], ANKLE_Z[leg["front"]], {leg["key"]: 0.0})
    bpy.context.view_layer.update()
    data = evaluated_paw_points(body, groups)
    lift = {}
    for leg in LEGS:
        group = f"{PAW_GROUP[leg['front']]}_{'L' if leg['side'] < 0 else 'R'}"
        _verts, _point, low = data[group]
        lift[leg["key"]] = -(low if low is not None else 0.0)
    remove_leg_rig(arm)
    return lift


def evaluated_paw_points(body, groups):
    """Lowest contact point per paw group on the evaluated (skinned) mesh, at the current frame."""
    depsgraph = bpy_evaluated()
    evaluated = body.evaluated_get(depsgraph)
    mesh = evaluated.to_mesh()
    mesh.calc_loop_triangles()
    index = {g.name: g.index for g in body.vertex_groups}
    members = {name: [] for name in groups}
    for i, v in enumerate(mesh.vertices):
        for g in v.groups:
            for name in groups:
                if g.group == index[name] and g.weight > 0.5:
                    members[name].append(i)
    points = {}
    lowest = {}
    for name, ids in members.items():
        if not ids:
            points[name] = None
            lowest[name] = None
            continue
        zs = [mesh.vertices[i].co.z for i in ids]
        low = min(zs)
        lowest[name] = low
        near = [mesh.vertices[i].co for i in ids if mesh.vertices[i].co.z <= low + 0.002]
        points[name] = (sum(p.x for p in near) / len(near), sum(p.y for p in near) / len(near))
    out = {name: (mesh.vertices, points[name], lowest[name]) for name in groups}
    evaluated.to_mesh_clear()
    return out


def bpy_evaluated():
    import bpy
    return bpy.context.evaluated_depsgraph_get()


def stance_frames(clip):
    """Per-leg planted frames from the footfall schedule (idle and sit: every paw every frame)."""
    frames = list(range(0, CLIPS[clip]["frames"] + 1, CLIPS[clip]["sample"]))
    if clip in ("idle", "sit"):
        return frames, {leg["key"]: frames for leg in LEGS}
    gait = GAITS[clip]
    cycle = CLIPS[clip]["frames"]
    planted = {leg["key"]: [] for leg in LEGS}
    for frame in frames:
        p = (frame / cycle) % 1.0
        for leg in LEGS:
            if (p + gait["offset"][leg["key"]]) % 1.0 < gait["duty"]:
                planted[leg["key"]].append(frame)
    return frames, planted


