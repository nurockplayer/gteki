#!/usr/bin/env python3
"""Build the #854 cat protagonist: scripted metaball body, armature, baked clips and GLB.

Everything is generated by this file: no addons, no downloads, no external assets. Deterministic.
Original work, CC0 1.0 (see assets/library/PROVENANCE.md).

Usage (Blender 5.2, headless, from the repository root):
  blender -b -P tools/blender/character/build_cat.py -- --out <dir> [--tabby] [--preview <dir>]
    --out      directory for cat.glb (or cat_tabby.glb with --tabby)
    --tabby    add mackerel stripes on the back, legs and tail
    --preview  render bind-pose and clip PNGs into this directory

Coordinates. The model is authored in Blender's Z-up frame: X = side (+X is the cat's right,
facing +Y), Y = forward (the nose is at +Y), Z = height (feet at 0). The glTF exporter's Y-up
conversion writes final GLB (x, z, -y), so the exported cat has Y up, feet at y = 0 and faces -Z,
the avatar contract avatarGlb.ts and the human GLB already assume.

The brief's element table is quoted in final GLB coordinates (x side, y height, z along the body
with + toward the head). GLB z = -Blender y, so a table +z (toward the head) is Blender +Y.
"""

