def build_body(tabby):
    import bpy

    mb = bpy.data.metaballs.new("cat_field")
    mb.resolution = 0.004
    mb.render_resolution = 0.004
    mb.threshold = THRESHOLD
    obj = bpy.data.objects.new("cat_field", mb)
    bpy.context.scene.collection.objects.link(obj)

    def element(x, height, along, rx, ry, rz):
        el = mb.elements.new(type='ELLIPSOID')
        el.co = (x, along, height)
        el.stiffness = STIFFNESS
        # ELLIPSOID sizes follow world axes: x side, y along, z height.
        el.size_x = rx * SIZE_K * SIZE_SHRINK
        el.size_y = rz * SIZE_K * SIZE_SHRINK
        el.size_z = ry * SIZE_K * SIZE_SHRINK
        return el

    for _name, x, height, along, rx, ry, rz in ELEMENTS:
        element(x, height, along, rx, ry, rz)
    for height, along, radius in TAIL_PATH:
        # Elongated along the body so neighbouring elements share one field and fuse into a tail.
        element(0.0, height, along, radius, radius, max(radius, 0.034))

    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    bpy.ops.object.convert(target='MESH')
    body = bpy.context.object
    body.name = "cat_body"

    mod = body.modifiers.new("remesh", 'REMESH')
    mod.mode = 'VOXEL'
    mod.voxel_size = VOXEL_M
    mod.use_smooth_shade = True
    bpy.ops.object.modifier_apply(modifier=mod.name)

    mod = body.modifiers.new("smooth", 'SMOOTH')
    mod.factor = 0.5
    mod.iterations = 3
    bpy.ops.object.modifier_apply(modifier=mod.name)

    body.data.calc_loop_triangles()
    _print_bounds("INFO body after remesh", body.data)
    current = len(body.data.loop_triangles)
    mod = body.modifiers.new("decimate", 'DECIMATE')
    mod.decimate_type = 'COLLAPSE'
    mod.ratio = max(0.01, min(1.0, BODY_TRI_TARGET / max(current, 1)))
    bpy.ops.object.modifier_apply(modifier=mod.name)
    body.data.calc_loop_triangles()

    for poly in body.data.polygons:
        poly.use_smooth = True

    # Feet on the floor: drop the whole build by its lowest point (the paw soles).
    dz = -min(v.co.z for v in body.data.vertices)
    for v in body.data.vertices:
        v.co.z += dz
    return body, dz


def _print_bounds(label, mesh):
    xs = [v.co.x for v in mesh.vertices]
    ys = [v.co.y for v in mesh.vertices]
    zs = [v.co.z for v in mesh.vertices]
    print(f"{label}: x {min(xs):.3f}..{max(xs):.3f} y {min(ys):.3f}..{max(ys):.3f} z {min(zs):.3f}..{max(zs):.3f}")


def fix_body_colours(body, tabby):
    import bpy
    mesh = body.data
    attr = mesh.color_attributes.new(name="Col", type='FLOAT_COLOR', domain='POINT')
    for i, v in enumerate(mesh.vertices):
        attr.data[i].color = (*body_colour(v.co, tabby), 1.0)
    _set_active_colour(mesh, attr)


def _set_active_colour(mesh, attr):
    mesh.color_attributes.active_color = attr
    try:
        mesh.color_attributes.render_color_index = list(mesh.color_attributes).index(attr)
    except (AttributeError, ValueError):
        pass


