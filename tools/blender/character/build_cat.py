def fail(message):
    raise SystemExit("build_cat: " + message)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--tabby", action="store_true")
    parser.add_argument("--preview", type=Path, default=None)
    args = parser.parse_args(sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else [])

    import bpy
    bpy.ops.wm.read_factory_settings(use_empty=True)
    for obj in list(bpy.data.objects):
        bpy.data.objects.remove(obj, do_unlink=True)
    scene = bpy.context.scene
    scene.render.fps, scene.render.fps_base = FPS, 1.0

    checker = Checker()
    body, dz = build_body(args.tabby)
    fix_body_colours(body, args.tabby)

    def luma(channel):
        return 0.2126 * channel[0] + 0.7152 * channel[1] + 0.0722 * channel[2]

    if args.tabby:
        attribute = body.data.color_attributes["Col"]
        darker = total = 0
        for i, vertex in enumerate(body.data.vertices):
            if coat_t(vertex.co) < 0.5:
                continue
            total += 1
            if luma(attribute.data[i].color) <= 0.75 * luma(body_colour(vertex.co, False)):
                darker += 1
        share = darker / max(total, 1)
        checker.check(total > 0 and share >= 0.20,
                      f"tabby {share * 100:.0f} % of {total} back vertices >= 25 % darker than grey (>= 20 %)")

    mesh = body.data
    checker.check(mesh_triangles(mesh) <= BODY_TRI_TARGET * 1.1, f"body triangles {mesh_triangles(mesh)}")
    components = body_components(mesh)
    checker.check(components == 1, f"body is one component ({components})")
    checker.check(not non_manifold_edges(mesh), f"body is manifold ({len(non_manifold_edges(mesh))} bad edges)")
    loops = section_loops(mesh, 0.06)
    checker.check(len(loops) == 4, f"leg section at z=0.06 has four islands ({len(loops)})")

    arm = build_armature(dz)
    skin_body(body, arm)
    shells = build_shells(dz, args.tabby)
    bpy.ops.object.select_all(action='DESELECT')
    body.select_set(True)
    shells.select_set(True)
    bpy.context.view_layer.objects.active = body
    bpy.ops.object.join()
    body = bpy.context.object
    body.name = "VIS_cat"

    modifier = body.modifiers.new("Armature", 'ARMATURE')
    modifier.object = arm
    body.parent = arm
    body.matrix_parent_inverse = arm.matrix_world.inverted()

    rigid = rigid_paws(body, arm)
    smooth_weights(body, rigid)
    bpy.context.view_layer.objects.active = body
    bpy.ops.object.vertex_group_limit_total(group_select_mode='ALL', limit=4)
    bpy.ops.object.vertex_group_normalize_all(group_select_mode='ALL', lock_active=False)

    material = bpy.data.materials.new("cat_coat")
    material.use_nodes = True
    nodes = material.node_tree.nodes
    bsdf = nodes.get("Principled BSDF")
    bsdf.inputs["Roughness"].default_value = 0.72
    attribute = nodes.new("ShaderNodeVertexColor")
    attribute.layer_name = "Col"
    material.node_tree.links.new(attribute.outputs["Color"], bsdf.inputs["Base Color"])
    body.data.materials.clear()
    body.data.materials.append(material)

    body.data.calc_loop_triangles()
    checker.check(mesh_triangles(body.data) <= TRI_BUDGET, f"mesh triangles {mesh_triangles(body.data)} <= {TRI_BUDGET}")
    worst = max((len(v.groups) for v in body.data.vertices), default=0)
    checker.check(worst <= 4, f"max {worst} bone influences per vertex (<= 4)")

    groups = [paw_group(leg) for leg in LEGS]
    spine_groups = {g.index for g in body.vertex_groups if g.name in ("spine_01", "spine_02", "spine_03")}
    belly = [v.index for v in body.data.vertices
             if -0.10 < v.co.y < 0.08 and v.groups
             and max(v.groups, key=lambda g: g.weight).group in spine_groups]
    spine_rest = arm.data.bones["spine_02"].head_local.z
    offsets = stance_offset(arm, body, groups)
    print("INFO stance offsets: " + ", ".join(f"{k} {v * 1000:+.1f} mm" for k, v in offsets.items()))

    sit, hip = sit_setup(arm, offsets)
    # The sit hocks start at 18 mm; put the far paw exactly on the floor, then re-place the pose.
    heights = sit_paw_heights(arm, body, groups, sit)
    drop = -(heights["hind_L"] if heights["hind_L"] is not None else 0.0)
    for key in ("hind_L", "hind_R"):
        x, y, z = sit["targets"][key]
        sit["targets"][key] = (x, y, z + drop)
    heights = sit_paw_heights(arm, body, groups, sit)
    print(f"INFO sit hip z {hip.z:.3f} m, hind paw {heights}")

    actions = {}
    for clip in CLIPS:
        actions[clip] = bake_clip(arm, body, clip, offsets, sit)
        print(f"INFO baked {clip}: {CLIPS[clip]['frames']} frames, {len(action_fcurves(actions[clip]))} curves")

    # Bind-pose bounds (rest pose, no action): rump from the spine-weighted body, nose from the muzzle.
    arm.animation_data.action = None
    scene.frame_set(0)
    reset_pose(arm)
    bpy.context.view_layer.update()
    coords = [v.co for v in body.data.vertices]
    nose = max(c.y for c in coords)
    from mathutils import Vector
    tail_segments = [(Vector(row[1]), Vector(row[2])) for row in bone_table(dz) if row[0].startswith("tail")]
    rump = min((v.co.y for v in body.data.vertices
                if v.co.z >= 0.10
                and all(point_segment_distance(v.co, head, tail) > 0.022 for head, tail in tail_segments)), default=0.0)
    top = max(c.z for c in coords)
    checker.check(0.28 <= top <= 0.32, f"head top with ears {top:.3f} m (0.28-0.32)")
    checker.check(0.44 <= nose - rump <= 0.50, f"nose to rump {nose - rump:.3f} m (0.44-0.50)")
    checker.check(abs(min(c.z for c in coords)) <= 0.002, f"feet at 0 ({min(c.z for c in coords):.4f})")

    for clip in CLIPS:
        arm.animation_data.action = actions[clip]
        frames, planted = stance_frames(clip)
        speed = CALIB.get(clip, 0.0)
        contacts = {}
        lowest = {leg["key"]: 1.0 for leg in LEGS}
        bend = {leg["key"]: 1e9 for leg in LEGS}
        midline = 1e9
        body_low, spine_worst, tail_tip = 1.0, 0.0, -1.0
        for frame in frames:
            scene.frame_set(frame)
            data = evaluated_paw_points(body, groups)
            evaluated = body.evaluated_get(bpy.context.evaluated_depsgraph_get())
            skinned = evaluated.to_mesh()
            body_low = min(body_low, min((skinned.vertices[i].co.z for i in belly), default=1.0))
            evaluated.to_mesh_clear()
            spine_worst = max(spine_worst, abs(arm.pose.bones["spine_02"].head.z - spine_rest))
            tail_tip = max(tail_tip, arm.pose.bones["tail_04"].tail.z)
            for leg in LEGS:
                info = data[paw_group(leg)]
                contacts[(frame, leg["key"])] = info[0]
                if info[1] is not None:
                    lowest[leg["key"]] = min(lowest[leg["key"]], info[1])
                upper, lower, _paw = (arm.pose.bones[n] for n in leg_names(leg["front"], leg["side"]))
                start, mid, end = upper.head.copy(), lower.head.copy(), lower.tail.copy()
                for joint in (start, mid, end):
                    midline = min(midline, abs(joint.x))
                cross = ((end.y - start.y) * (mid.z - start.z) - (end.z - start.z) * (mid.y - start.y))
                margin = cross if not leg["front"] else -cross
                bend[leg["key"]] = min(bend[leg["key"]], margin)
        for leg in LEGS:
            checker.check(abs(lowest[leg["key"]]) <= 0.005,
                          f"{clip} {leg['key']} lowest paw {lowest[leg['key']]:.4f} m (within 5 mm of 0)")
        for leg in LEGS:
            label = "hind knee in front of the hip-hock line" if not leg["front"] else "fore elbow behind the shoulder-wrist line"
            checker.check(bend[leg["key"]] >= 0.0, f"{clip} {leg['key']} {label} ({bend[leg['key']]:.5f})")
        checker.check(midline >= 0.015, f"{clip} every leg joint |x| >= 0.015 ({midline:.4f})")
        for leg in LEGS:
            drift = 0.0
            run_start = None
            for frame in frames:
                if frame not in planted[leg["key"]]:
                    run_start = None
                    continue
                point = contacts[(frame, leg["key"])]
                if point is None:
                    drift = max(drift, 1.0)
                    continue
                if run_start is None:
                    run_start = (frame, point)
                else:
                    t = (frame - run_start[0]) / FPS
                    expected_y = run_start[1][1] - speed * t
                    drift = max(drift, abs(point[0] - run_start[1][0]), abs(point[1] - expected_y))
            checker.check(drift <= 0.01, f"{clip} {leg['key']} planted drift {drift * 1000:.1f} mm (<= 10)")
        if clip in GAITS:
            floor = 0.05 if clip == "run" else 0.07
            checker.check(body_low >= floor, f"{clip} lowest body vertex {body_low:.3f} m (>= {floor})")
            checker.check(spine_worst <= 0.035, f"{clip} spine_02 height within {spine_worst * 1000:.0f} mm of rest (<= 35)")
        if clip == "sit":
            checker.check(tail_tip <= 0.04, f"sit tail tip z {tail_tip:.3f} m (<= 0.04)")

    # Extras on the armature node: the clip calibration speeds read at runtime.
    arm["gteki_cat"] = {"calib": dict(CALIB)}
    arm.animation_data.action = bpy.data.actions["idle"]
    scene.frame_set(0)

    name = "cat_tabby.glb" if args.tabby else "cat.glb"
    out = export_glb(arm, body, args.out / name)
    triangles, size = check_glb(out, checker)

    if args.preview:
        render_previews(args.preview, arm)

    if checker.failures:
        print(f"FAILED {len(checker.failures)} check(s):")
        for message in checker.failures:
            print("  - " + message)
        sys.exit(1)
    print(f"OK {out} ({triangles} triangles, {size} bytes); extras gteki_cat.calib {CALIB}")


if __name__ == "__main__":
    main()
