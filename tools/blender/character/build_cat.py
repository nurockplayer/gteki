def leg_names(front, side):
    suffix = "L" if side < 0 else "R"
    prefix = "foreleg" if front else "hindleg"
    return f"{prefix}_upper_{suffix}", f"{prefix}_lower_{suffix}", f"{PAW_GROUP[front]}_{suffix}"


def solve_leg(arm, leg, target, paw_angle):
    """Place one leg in its sagittal plane: hip/shoulder -> knee/elbow -> wrist/hock -> paw.

    The mid joint bends forward (+Y) on the hind leg and backward (-Y) on the foreleg. The distal
    target is clamped to 98% of the reach instead of stretching the limb.
    """
    import bpy
    from mathutils import Matrix, Vector

    upper_name, lower_name, paw_name = leg_names(leg["front"], leg["side"])
    upper, lower, paw = arm.pose.bones[upper_name], arm.pose.bones[lower_name], arm.pose.bones[paw_name]
    head = upper.head.copy()
    goal = Vector(target)
    l1, l2 = upper.bone.length, lower.bone.length
    delta = goal - head
    distance = delta.length
    limit = STANCE_RATIO * (l1 + l2)
    if distance > limit:
        goal = head + delta * (limit / distance)
        distance = limit
    distance = max(distance, abs(l1 - l2) + 1e-4)
    direction = (goal - head) / distance
    along = (distance * distance + l1 * l1 - l2 * l2) / (2.0 * distance)
    height = math.sqrt(max(0.0, l1 * l1 - along * along))
    # In-plane perpendicular rotated +90 degrees about X: (y, z) -> (-z, y).
    perpendicular = Vector((0.0, -direction.z, direction.y))
    knee = head + direction * along + perpendicular * (height if not leg["front"] else -height)

    def orient(bone, start, end):
        matrix = (end - start).to_track_quat('Y', 'Z').to_matrix().to_4x4()
        matrix.translation = start
        bone.matrix = matrix
        bpy.context.view_layer.update()

    orient(upper, head, knee)
    orient(lower, knee, goal)
    rest = arm.data.bones[paw_name].matrix_local.to_3x3()
    matrix = (Matrix.Rotation(paw_angle, 3, 'X') @ rest).to_4x4()
    matrix.translation = goal
    paw.matrix = matrix
    bpy.context.view_layer.update()


def stance_offset(arm, body, groups):
    """Sole height of each paw in the rest pose, so stance targets can put it on z = 0."""
    import bpy
    if arm.animation_data is None:
        arm.animation_data_create()
    arm.animation_data.action = None
    for bone in arm.pose.bones:
        bone.matrix_basis.identity()
    bpy.context.view_layer.update()
    data = evaluated_paw_points(body, groups)
    return {leg["key"]: -(data[paw_group(leg)][1] if data[paw_group(leg)][1] is not None else 0.0)
            for leg in LEGS}


def paw_group(leg):
    return f"{PAW_GROUP[leg['front']]}_{'L' if leg['side'] < 0 else 'R'}"


