def render_previews(directory, arm):
    import bpy
    from mathutils import Vector
    scene = bpy.context.scene
    scene.render.engine = 'BLENDER_WORKBENCH'
    scene.render.resolution_x, scene.render.resolution_y = 1280, 800
    scene.render.resolution_percentage = 100
    scene.render.image_settings.file_format = 'PNG'
    shading = scene.display.shading
    shading.light = 'STUDIO'
    shading.show_shadows = True
    try:
        shading.color_type = 'VERTEX'
    except TypeError:
        shading.color_type = 'MATERIAL'
    shading.background_type = 'VIEWPORT'
    shading.background_color = (0.72, 0.74, 0.76)

    camera_data = bpy.data.cameras.new("preview_cam")
    camera_data.lens = 50.0
    camera = bpy.data.objects.new("preview_cam", camera_data)
    scene.collection.objects.link(camera)
    scene.camera = camera

    def shot(name, location, target, clip=None, frame=0):
        if clip:
            arm.animation_data.action = bpy.data.actions[clip]
            scene.frame_set(frame)
        else:
            arm.animation_data.action = None
            reset_pose(arm)
            scene.frame_set(0)
            bpy.context.view_layer.update()
        camera.location = Vector(location)
        direction = Vector(target) - Vector(location)
        camera.rotation_euler = direction.to_track_quat('-Z', 'Y').to_euler()
        directory.mkdir(parents=True, exist_ok=True)
        scene.render.filepath = str(directory / f"{name}.png")
        bpy.ops.render.render(write_still=True)
        print(f"preview {scene.render.filepath}")

    side = ((1.25, -0.10, 0.16), (0.0, -0.10, 0.16))
    shot("bind_side", *side)
    shot("bind_front", (0.0, 1.0, 0.17), (0.0, 0.0, 0.16))
    shot("bind_q45", (0.72, 0.72, 0.34), (0.0, -0.05, 0.15))
    shot("bind_back", (0.0, -1.25, 0.20), (0.0, 0.0, 0.16))
    shot("bind_q45back", (-0.72, -0.80, 0.30), (0.0, -0.08, 0.15))
    shot("bind_face", (0.09, 0.52, 0.27), (0.0, 0.19, 0.235))
    shot("sit_side", *side, "sit", 60)
    shot("sit_q45", (0.72, 0.72, 0.34), (0.0, -0.05, 0.15), "sit", 60)
    for frame in (0, 9, 18):
        shot(f"walk_side_{frame:02d}", *side, "walk", frame)
    shot("trot_side", *side, "trot", 6)
    shot("run_side", *side, "run", 4)


