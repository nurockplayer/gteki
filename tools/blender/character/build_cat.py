def glb_json(path):
    data = Path(path).read_bytes()
    magic, _version, _length = struct.unpack_from("<4sII", data, 0)
    if magic != b"glTF":
        raise ValueError("not a GLB")
    length = struct.unpack_from("<I", data, 12)[0]
    return json.loads(data[20:20 + length])


def export_glb(arm, body, out_path):
    import bpy
    bpy.ops.object.select_all(action='DESELECT')
    arm.select_set(True)
    body.select_set(True)
    bpy.context.view_layer.objects.active = arm
    properties = {prop.identifier: prop for prop in bpy.ops.export_scene.gltf.get_rna_type().properties}
    wanted = dict(
        export_format='GLB', use_selection=True, export_yup=True, export_apply=False,
        export_extras=True, export_skins=True, export_animations=True, export_morph=False,
        export_animation_mode='ACTIONS', export_nla_strips=False, export_anim_single_armature=True,
        export_frame_range=False, export_force_sampling=False, export_frame_step=1,
        export_optimize_animation_size=True, export_optimize_animation_keep_anim_armature=False,
        export_def_bones=False, export_leaf_bone=False, export_armature_object_remove=False,
        export_rest_position_armature=True, export_anim_slide_to_zero=True,
        export_texcoords=False, export_normals=True, export_tangents=False,
        export_materials='EXPORT', export_vertex_color='MATERIAL', export_all_vertex_colors=False,
        export_cameras=False, export_lights=False, export_draco_mesh_compression_enable=False,
    )
    options = {k: v for k, v in wanted.items() if k in properties}
    for required in ("export_format", "export_extras", "export_skins", "export_animations", "export_yup"):
        if required not in options:
            fail(f"glTF exporter is missing {required}")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    tmp = out_path.with_name(f".{out_path.stem}.export.glb")
    status = bpy.ops.export_scene.gltf(filepath=str(tmp), **options)
    if "FINISHED" not in status:
        fail(f"glTF export failed: {status}")
    tmp.replace(out_path)
    return out_path


def check_glb(path, checker):
    doc = glb_json(path)
    meshes = doc.get("meshes", [])
    checker.check(len(meshes) == 1, f"GLB has one mesh ({len(meshes)})")
    mesh = meshes[0] if meshes else {"primitives": []}
    checker.check(len(mesh.get("primitives", [])) == 1, "GLB mesh has one primitive")
    checker.check(len(doc.get("materials", [])) == 1, f"GLB has one material ({len(doc.get('materials', []))})")
    checker.check(not doc.get("images") and not doc.get("textures"), "GLB has no textures")
    triangles = 0
    for primitive in mesh.get("primitives", []):
        checker.check("COLOR_0" in primitive["attributes"], "GLB primitive carries COLOR_0")
        if "indices" in primitive:
            triangles += doc["accessors"][primitive["indices"]]["count"] // 3
        else:
            triangles += doc["accessors"][primitive["attributes"]["POSITION"]]["count"] // 3
    checker.check(triangles <= TRI_BUDGET, f"GLB triangles {triangles} <= {TRI_BUDGET}")
    names = sorted(animation.get("name", "") for animation in doc.get("animations", []))
    checker.check(names == sorted(CLIPS), f"GLB clips {names}")
    root = next((n for n in doc.get("nodes", []) if n.get("extras", {}).get("gteki_cat")), None)
    calib = (root or {}).get("extras", {}).get("gteki_cat", {}).get("calib", {})
    checker.check(calib == CALIB, f"GLB extras gteki_cat.calib {calib}")
    where = doc["accessors"][mesh["primitives"][0]["attributes"]["POSITION"]]
    y_min, y_max = where["min"][1], where["max"][1]
    checker.check(abs(y_min) <= 0.005, f"GLB feet at y = {y_min:.4f}")
    checker.check(0.28 <= y_max <= 0.32, f"GLB height {y_max:.3f} m with ears")
    # Faces -Z: the nose (largest |z| on the head end) must be at negative z.
    checker.check(where["min"][2] < 0.0 < where["max"][2], "GLB nose at -Z, tail at +Z")
    print(f"INFO GLB {path.name}: {triangles} triangles, {path.stat().st_size} bytes")
    return triangles, path.stat().st_size


