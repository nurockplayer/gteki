def catmull(p, t):
    n = len(p) - 1
    i = min(int(t * n), n - 1)
    u = t * n - i
    a, b, c, d = p[max(i - 1, 0)], p[i], p[i + 1], p[min(i + 2, n)]
    return tuple(0.5 * ((2 * b[k]) + (-a[k] + c[k]) * u + (2 * a[k] - 5 * b[k] + 4 * c[k] - d[k]) * u * u
                        + (-a[k] + 3 * b[k] - 3 * c[k] + d[k]) * u ** 3) for k in range(6))


def build_body(tabby):
    import bmesh
    import bpy
    from mathutils import Matrix, Vector

    bm = bmesh.new()

    def blob(node):
        matrix = Matrix.Translation(node[:3]) @ Matrix.Diagonal((node[3], node[4], node[5], 1))
        bmesh.ops.create_uvsphere(bm, u_segments=14, v_segments=10, radius=1.0, matrix=matrix)

    def sweep(points):
        length = sum((Vector(points[i + 1][:3]) - Vector(points[i][:3])).length for i in range(len(points) - 1))
        steps = max(4, int(length / 0.003))
        for i in range(steps + 1):
            blob(catmull(points, i / steps))

    for chain in (TORSO, TAIL, fore_nodes(1), fore_nodes(-1), hind_nodes(1), hind_nodes(-1)):
        sweep(chain)
    for node in SINGLES:
        blob(node)
    mesh = bpy.data.meshes.new("cat_body")
    bm.to_mesh(mesh)
    bm.free()
    body = bpy.data.objects.new("cat_body", mesh)
    bpy.context.scene.collection.objects.link(body)
    bpy.context.view_layer.objects.active = body
    body.select_set(True)

    mod = body.modifiers.new("remesh", 'REMESH')
    mod.mode = 'VOXEL'
    mod.voxel_size = VOXEL_M
    bpy.ops.object.modifier_apply(modifier=mod.name)
    mod = body.modifiers.new("smooth", 'SMOOTH')
    mod.factor = 0.6
    mod.iterations = 6
    bpy.ops.object.modifier_apply(modifier=mod.name)

    mesh = body.data
    mesh.calc_loop_triangles()
    _print_bounds("INFO body after remesh", mesh)
    current = len(mesh.loop_triangles)
    mod = body.modifiers.new("decimate", 'DECIMATE')
    mod.decimate_type = 'COLLAPSE'
    mod.ratio = max(0.01, min(1.0, BODY_TRI_TARGET / max(current, 1)))
    bpy.ops.object.modifier_apply(modifier=mod.name)
    mesh = body.data
    mesh.calc_loop_triangles()
    for poly in mesh.polygons:
        poly.use_smooth = True

    # Feet on the floor: drop the whole build by its lowest point.
    dz = -min(v.co.z for v in mesh.vertices)
    for v in mesh.vertices:
        v.co.z += dz
    return body, dz


def _print_bounds(label, mesh):
    xs = [v.co.x for v in mesh.vertices]
    ys = [v.co.y for v in mesh.vertices]
    zs = [v.co.z for v in mesh.vertices]
    print(f"{label}: x {min(xs):.3f}..{max(xs):.3f} y {min(ys):.3f}..{max(ys):.3f} z {min(zs):.3f}..{max(zs):.3f}")


def fix_body_colours(body, tabby):
    mesh = body.data
    attr = mesh.color_attributes.new(name="Col", type='FLOAT_COLOR', domain='POINT')
    for i, v in enumerate(mesh.vertices):
        attr.data[i].color = (*body_colour(v.co, tabby), 1.0)
    _set_active_colour(mesh, attr)


def _set_active_colour(mesh, attr):
    mesh.color_attributes.active_color = attr
    try:
        mesh.color_attributes.render_color_index = list(mesh.color_attributes).index(attr)
    except (AttributeError, ValueError):
        pass


