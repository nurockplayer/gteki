def add_leg_rig(arm, targets, poles, world):
    for leg in LEGS:
        front = leg["front"]
        suffix = "L" if leg["side"] < 0 else "R"
        prefix = "foreleg" if front else "hindleg"
        lower = arm.pose.bones[f"{prefix}_lower_{suffix}"]
        c = lower.constraints.new('IK')
        c.target = targets[leg["key"]]
        c.chain_count = 2
        c.pole_target = poles[leg["key"]]
        # Foreleg elbows point backward, hind knees forward; the pole sits on that side.
        c.pole_angle = math.radians(-90.0)
        paw = arm.pose.bones[f"{PAW_GROUP[front]}_{suffix}"]
        cr = paw.constraints.new('COPY_ROTATION')
        cr.target = world
        cr.owner_space = 'WORLD'
        cr.target_space = 'WORLD'


def remove_leg_rig(arm):
    import bpy
    for bone in arm.pose.bones:
        for constraint in list(bone.constraints):
            bone.constraints.remove(constraint)


def make_empties():
    import bpy
    targets, poles = {}, {}
    world = bpy.data.objects.new("PawWorld", None)
    bpy.context.scene.collection.objects.link(world)
    for leg in LEGS:
        front = leg["front"]
        s = leg["side"]
        t = bpy.data.objects.new(f"IK_{leg['key']}", None)
        t.empty_display_size = 0.02
