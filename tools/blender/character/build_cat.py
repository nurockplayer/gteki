def mesh_triangles(mesh):
    mesh.calc_loop_triangles()
    return len(mesh.loop_triangles)


def body_components(mesh):
    parent = list(range(len(mesh.vertices)))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    for edge in mesh.edges:
        ra, rb = find(edge.vertices[0]), find(edge.vertices[1])
        if ra != rb:
            parent[rb] = ra
    return len({find(i) for i in range(len(mesh.vertices))})


def non_manifold_edges(mesh):
    counts = {}
    for poly in mesh.polygons:
        n = len(poly.vertices)
        for i in range(n):
            a, b = poly.vertices[i], poly.vertices[(i + 1) % n]
            key = (min(a, b), max(a, b))
            counts[key] = counts.get(key, 0) + 1
    return [key for key, count in counts.items() if count != 2]


def section_loops(mesh, height, tolerance=1e-5):
    """Closed loops of the horizontal slice at `height`, as sets of intersection points."""
    segments = []
    verts = [v.co for v in mesh.vertices]
    for poly in mesh.polygons:
        idx = list(poly.vertices)
        crossings = []
        for i in range(len(idx)):
            a, b = verts[idx[i]], verts[idx[(i + 1) % len(idx)]]
            da, db = a.z - height, b.z - height
            if (da < 0.0 <= db) or (db < 0.0 <= da):
                crossings.append(a.lerp(b, da / (da - db)))
        if len(crossings) == 2:
            segments.append((crossings[0], crossings[1]))
    if not segments:
        return []
    def key(point):
        return (round(point.x / tolerance), round(point.y / tolerance), round(point.z / tolerance))
    graph = {}
    for a, b in segments:
        graph.setdefault(key(a), []).append(key(b))
        graph.setdefault(key(b), []).append(key(a))
    seen, loops = set(), []
    for start in graph:
        if start in seen:
            continue
        stack, component = [start], set()
        while stack:
            node = stack.pop()
            if node in component:
                continue
            component.add(node)
            stack.extend(n for n in graph[node] if n not in component)
        seen |= component
        loops.append(component)
    return loops


def evaluated_paw_points(body, groups):
    """Lowest contact point per paw group on the evaluated (skinned) mesh, at the current frame."""
    import bpy
    depsgraph = bpy.context.evaluated_depsgraph_get()
    evaluated = body.evaluated_get(depsgraph)
    mesh = evaluated.to_mesh()
    mesh.calc_loop_triangles()
    index = {g.name: g.index for g in body.vertex_groups}
    members = {name: [] for name in groups}
    for i, v in enumerate(mesh.vertices):
        for g in v.groups:
            for name in groups:
                if g.group == index[name] and g.weight > 0.5:
                    members[name].append(i)
    points = {}
    lowest = {}
    for name, ids in members.items():
        if not ids:
            points[name] = None
            lowest[name] = None
            continue
        zs = [mesh.vertices[i].co.z for i in ids]
        low = min(zs)
        lowest[name] = low
        near = [mesh.vertices[i].co for i in ids if mesh.vertices[i].co.z <= low + 0.002]
        points[name] = (sum(p.x for p in near) / len(near), sum(p.y for p in near) / len(near))
    out = {name: (points[name], lowest[name]) for name in groups}
    evaluated.to_mesh_clear()
    return out


def stance_frames(clip):
    """Per-leg planted frames from the footfall schedule (idle and sit: every paw every frame)."""
    frames = list(range(0, CLIPS[clip]["frames"] + 1, CLIPS[clip]["sample"]))
    if clip in ("idle", "sit"):
        return frames, {leg["key"]: frames for leg in LEGS}
    gait = GAITS[clip]
    cycle = CLIPS[clip]["frames"]
    planted = {leg["key"]: [] for leg in LEGS}
    for frame in frames:
        p = (frame / cycle) % 1.0
        for leg in LEGS:
            if (p + gait["offset"][leg["key"]]) % 1.0 < gait["duty"]:
                planted[leg["key"]].append(frame)
    return frames, planted


