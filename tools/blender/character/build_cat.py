def build_armature(dz):
    import bpy
    data = bpy.data.armatures.new("ARM_cat")
    arm = bpy.data.objects.new("ARM_cat", data)
    bpy.context.scene.collection.objects.link(arm)
    bpy.context.view_layer.objects.active = arm
    arm.select_set(True)
    bpy.ops.object.mode_set(mode='EDIT')
    for name, head, tail, parent, connected, deform in bone_table(dz):
        eb = data.edit_bones.new(name)
        eb.head, eb.tail, eb.roll = head, tail, 0.0
        eb.use_deform = deform
        if parent:
            eb.parent = data.edit_bones[parent]
            eb.use_connect = connected
    bpy.ops.object.mode_set(mode='OBJECT')
    if len(data.bones) != 24:
        fail(f"armature has {len(data.bones)} bones, expected 24")
    return arm


