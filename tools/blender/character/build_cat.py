def build_shells(dz, tabby):
    import bmesh
    import bpy
    from mathutils import Matrix, Vector

    bm = bmesh.new()
    colours = []   # (vertex, rgb)
    groups = []    # (vertices, group name)

    def add_verts(points, colour, group):
        verts = [bm.verts.new(p) for p in points]
        colours.extend((v, colour) for v in verts)
        groups.append((verts, group))
        return verts

    def ear(side):
        s = side
        thickness = 0.006
        base_w, height = 0.030, 0.035
        tri = [(-base_w / 2, 0.0), (base_w / 2, 0.0), (0.0, height)]
        rot = Matrix.Rotation(math.radians(20.0) * s, 4, 'Y') @ Matrix.Rotation(math.radians(-12.0), 4, 'X')
        origin = Vector((s * 0.022, 0.213, 0.272 + dz))
        front, back = [], []
        for x, z in tri:
            front.append(origin + rot @ Vector((x, thickness / 2, z)))
            back.append(origin + rot @ Vector((x, -thickness / 2, z)))
        fv = add_verts([tuple(p) for p in front], INNER_EAR_L, f"ear_{'L' if s < 0 else 'R'}")
        bv = add_verts([tuple(p) for p in back], body_colour((s * 0.03, 0.20, 0.27), tabby),
                       f"ear_{'L' if s < 0 else 'R'}")
        bm.faces.new(fv)
        bm.faces.new(list(reversed(bv)))
        for i in range(3):
            j = (i + 1) % 3
            bm.faces.new((fv[i], fv[j], bv[j], bv[i]))

    def ellipsoid(centre, normal, radii, colour, group, slant=0.0, segments=6, rings=4):
        tmp = bmesh.new()
        bmesh.ops.create_uvsphere(tmp, u_segments=segments, v_segments=rings, radius=1.0)
        n = Vector(normal).normalized()
        rot = n.to_track_quat('X', 'Z').to_matrix().to_4x4()
        rot = rot @ Matrix.Rotation(slant, 4, 'X')
        mat = Matrix.Translation(Vector(centre)) @ rot @ Matrix.Diagonal(Vector(radii).to_4d())
        bmesh.ops.transform(tmp, matrix=mat, verts=tmp.verts)
        mapping = {}
        for v in tmp.verts:
            nv = bm.verts.new(v.co.copy())
            mapping[v] = nv
            colours.append((nv, colour))
        for f in tmp.faces:
            bm.faces.new([mapping[v] for v in f.verts])
        groups.append((list(mapping.values()), group))
        tmp.free()

    # Skull ellipsoid, for placing the eyes on its surface.
    skull_c = Vector((0.0, 0.225, 0.255 + dz))
    skull_r = Vector((0.043, 0.042, 0.037))
    for s in (-1, 1):
        direction = Vector((s * 0.62, 0.68, 0.20)).normalized()
        t = 1.0 / math.sqrt(sum((direction[i] / skull_r[i]) ** 2 for i in range(3)))
        surface = skull_c + direction * t
        n = Vector(((surface.x - skull_c.x) / skull_r.x ** 2, (surface.y - skull_c.y) / skull_r.y ** 2,
                    (surface.z - skull_c.z) / skull_r.z ** 2)).normalized()
        centre = surface - n * 0.005
        ellipsoid(centre, n, (0.010, 0.0095, 0.0065), EYE_L, "head", slant=math.radians(14.0) * s)
        ellipsoid(centre + n * 0.0060, n, (0.0022, 0.0065, 0.0020), PUPIL_L, "head", slant=math.radians(14.0) * s,
                  segments=5, rings=3)
    ear(-1)
    ear(1)
    # Nose: a small wedge at the muzzle tip, rotated as a diamond.
    nose_c = Vector((0.0, 0.281, 0.243 + dz))
    rot = Matrix.Rotation(math.radians(45.0), 4, 'Y')
    nose = add_verts([tuple(nose_c + rot @ Vector(p)) for p in (
        (-0.006, 0.003, 0.0), (0.006, 0.003, 0.0), (0.006, -0.003, 0.0), (-0.006, -0.003, 0.0),
        (0.0, 0.003, 0.008), (0.0, -0.003, 0.008),
    )], NOSE_L, "head")
    for face in ((0, 1, 2, 3), (4, 5, 1, 0), (5, 4, 3, 2), (0, 4, 1), (1, 5, 2), (2, 3, 4), (3, 0, 5)):
        try:
            bm.faces.new([nose[i] for i in face])
        except ValueError:
            pass

    bm.verts.index_update()
    indices = {}
    for verts, group in groups:
        indices.setdefault(group, []).extend(v.index for v in verts)
    mesh = bpy.data.meshes.new("cat_shells")
    bm.to_mesh(mesh)
    bm.free()
    for poly in mesh.polygons:
        poly.use_smooth = False
    obj = bpy.data.objects.new("cat_shells", mesh)
    bpy.context.scene.collection.objects.link(obj)
    attr = mesh.color_attributes.new(name="Col", type='FLOAT_COLOR', domain='POINT')
    # bmesh vertex order is stable through to_mesh, so the recorded order maps 1:1.
    for i, (_v, colour) in enumerate(colours):
        attr.data[i].color = (*colour, 1.0)
    _set_active_colour(mesh, attr)
    for group, ids in indices.items():
        vg = obj.vertex_groups.new(name=group)
        vg.add(ids, 1.0, 'REPLACE')
    return obj


