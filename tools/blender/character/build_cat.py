def paw_angle_for(leg, phase, gait):
    """Paw pitch: rest orientation in stance, up to 35 degrees toe-down through swing."""
    if phase % 1.0 < gait["duty"]:
        return 0.0
    s = (phase % 1.0 - gait["duty"]) / (1.0 - gait["duty"])
    return -math.radians(35.0) * math.sin(math.pi * s) ** 2


def foot_path(front, phase, gait, offset):
    """Distal joint (wrist/hock) target: stance moves backward at exactly the stride speed.

    The stance range is centred on the shoulder (fore) or the hip (hind) so neither end of the
    travel leaves the leg's comfortable reach.
    """
    centre, rest_z = STANCE_CENTRE[front], REST_DISTAL[front][1]
    duty, travel = gait["duty"], gait["travel"]
    p = phase % 1.0
    if p < duty:
        return centre + travel * (0.5 - p / duty), rest_z + offset
    s = (p - duty) / (1.0 - duty)
    ease = s * s * (3.0 - 2.0 * s)
    return centre + travel * (ease - 0.5), rest_z + offset + gait["lift"] * math.sin(math.pi * s) ** 2


def idle_pose(t, dz):
    breath = math.sin(math.tau * 3.0 * t / 8.0)
    look = math.radians(35.0) * math.sin(math.tau * t / 8.0)
    tail = math.sin(math.tau * t / 4.0)
    twitch = 0.30 * (math.exp(-((t - 2.1) / 0.09) ** 2) + math.exp(-((t - 5.4) / 0.09) ** 2))
    fk = {
        "spine_01": (0.010 * breath, 0.0, 0.0),
        "spine_02": (0.012 * breath, 0.0, 0.0),
        "spine_03": (0.008 * math.sin(math.tau * 3.0 * t / 8.0 + 0.4), 0.0, 0.0),
        "neck": (0.0, 0.0, look * 0.35),
        "head": (0.02 * breath, 0.0, look * 0.65),
        "ear_R": (-twitch, 0.0, 0.0),
        "tail_01": (-0.06, 0.0, 0.10 * tail),
        "tail_02": (0.0, 0.0, 0.14 * math.sin(math.tau * t / 4.0 - 0.6)),
        "tail_03": (0.0, 0.0, 0.16 * math.sin(math.tau * t / 4.0 - 1.2)),
        "tail_04": (0.03, 0.0, 0.18 * math.sin(math.tau * t / 4.0 - 1.8)),
    }
    return dict(root=(0.0, 0.0, 0.002 * breath), fk=fk)


def sit_setup(arm, offsets):
    """Solve the static sitting body: spine up 32 degrees, shoulders at straight-leg height.

    The rump drops until the forelegs can stand vertical under the shoulders; the hind hocks sit
    on the floor with the paw bone laid flat, and the head counter-rotates level.
    """
    import bpy
    from mathutils import Vector
    pitch = math.radians(32.0)
    fk = {
        "spine_01": (pitch, 0.0, 0.0),
        "spine_02": (0.0, 0.0, 0.0),
        "spine_03": (0.0, 0.0, 0.0),
        "neck": (-0.42, 0.0, 0.0),
        "head": (-0.22, 0.0, 0.0),
        "ear_L": (0.0, 0.0, 0.0),
        "ear_R": (0.0, 0.0, 0.0),
        # Tail: counter-rotates the spine pitch and stays level on the floor, curling to one side.
        "tail_01": (-pitch - 0.28, 0.0, 0.85),
        "tail_02": (0.53, 0.0, 0.55),
        "tail_03": (0.63, 0.0, 0.45),
        "tail_04": (0.66, 0.0, 0.30),
    }
    fore_wrist_z = REST_DISTAL[True][1] + offsets["fore_L"]
    # Reach from the shoulder to the wrist that keeps the foreleg just short of straight.
    reach = STANCE_RATIO * (arm.data.bones["foreleg_upper_L"].length + arm.data.bones["foreleg_lower_L"].length)

    def apply(root_z):
        reset_pose(arm)
        arm.pose.bones["root"].location = (0.0, 0.0, root_z)
        set_fk(arm, fk)
        bpy.context.view_layer.update()

    apply(0.0)
    shoulder = arm.pose.bones["foreleg_upper_L"].head.copy()
    root_z = fore_wrist_z + reach - shoulder.z
    apply(root_z)
    shoulder = arm.pose.bones["foreleg_upper_L"].head.copy()
    hip = arm.pose.bones["hindleg_upper_L"].head.copy()
    hind_hock_z = 0.018
    # Far enough behind the hip that the folded leg is not at its minimum reach.
    hind_hock = Vector((0.0, hip.y - 0.055, hind_hock_z))
    # Flat paw bone: rotate the rest pitch (about 40.6 degrees down) back to horizontal.
    rest_dir = arm.data.bones["hindpaw_L"].tail_local - arm.data.bones["hindpaw_L"].head_local
    flat = math.atan2(-rest_dir.z, rest_dir.y)
    targets = {
        "fore_L": (-0.031, shoulder.y, fore_wrist_z),
        "fore_R": (0.031, shoulder.y, fore_wrist_z),
        "hind_L": (-0.036, hind_hock.y, hind_hock.z),
        "hind_R": (0.036, hind_hock.y, hind_hock.z),
    }
    pose = dict(root=(0.0, 0.0, root_z), fk=fk, targets=targets, paw={"hind_L": flat, "hind_R": flat})
    return pose, hip


def sit_paw_heights(arm, body, groups, pose):
    """Lowest hind-paw vertex with the sit pose applied, to lift the hocks onto the floor."""
    import bpy
    apply_pose(arm, pose, {})
    bpy.context.view_layer.update()
    data = evaluated_paw_points(body, groups)
    return {leg["key"]: data[paw_group(leg)][1] for leg in LEGS}


def locomotion_pose(clip, t, dz):
    gait = GAITS[clip]
    cycle_s = CLIPS[clip]["frames"] / FPS
    p = (t / cycle_s) % 1.0
    # Static body height: a root drop plus a small pitch that turns the chest/hip drops into the
    # two joint heights asked for, at the shoulder and the hip.
    theta = (gait["hip"] - gait["chest"]) / (SHOULDER_LEVER - HIP_LEVER)
    root_z = -gait["hip"] - HIP_LEVER * theta
    if clip == "walk":
        bob = 0.003 * math.sin(math.tau * 2.0 * p)
        flex, pitch = 0.0, 0.0
        sway = 0.03 * math.sin(math.tau * p)
        head = (-0.02 * math.sin(math.tau * 2.0 * p), 0.0, 0.02 * math.sin(math.tau * p))
        tail_base = (-0.10, 0.0, 0.06 * math.sin(math.tau * p))
    elif clip == "trot":
        bob = 0.003 * math.sin(math.tau * 2.0 * p)
        flex, pitch = 0.0, 0.0
        sway = 0.02 * math.sin(math.tau * p)
        head = (-0.03 * math.sin(math.tau * 2.0 * p), 0.0, 0.0)
        tail_base = (-0.16, 0.0, 0.05 * math.sin(math.tau * p))
    else:
        bob = 0.002 * math.sin(math.tau * p + 0.6)
        # +-8 degrees of spine flex, and a pitch that swings the other way so the chest keeps clear
        # of the floor at the bottom of the flex.
        flex = 0.14 * math.sin(math.tau * p + 0.9)
        pitch = -0.04 * math.sin(math.tau * p + 0.9)
        sway = 0.0
        head = (-0.6 * flex, 0.0, 0.0)
        tail_base = (-0.24, 0.0, 0.04 * math.sin(math.tau * p))
    fk = {
        "spine_01": (theta + pitch, 0.0, sway),
        "spine_02": (flex, 0.0, sway * 0.5),
        "spine_03": (flex * 0.5, 0.0, sway * 0.3),
        "neck": (head[0] * 0.4, 0.0, 0.0),
        "head": head,
        "tail_01": tail_base,
        "tail_02": (tail_base[0] * 0.4, 0.0, 0.05 * math.sin(math.tau * p - 0.5)),
        "tail_03": (tail_base[0] * 0.2, 0.0, 0.06 * math.sin(math.tau * p - 1.0)),
        "tail_04": (0.0, 0.0, 0.07 * math.sin(math.tau * p - 1.5)),
    }
    return dict(root=(0.0, 0.0, root_z + bob), fk=fk, gait=gait, phase=p)


def reset_pose(arm):
    for bone in arm.pose.bones:
        bone.rotation_mode = 'QUATERNION'
        bone.location = (0.0, 0.0, 0.0)
        bone.rotation_quaternion = (1.0, 0.0, 0.0, 0.0)
        bone.scale = (1.0, 1.0, 1.0)


def set_fk(arm, fk):
    from mathutils import Euler
    for name, angles in fk.items():
        arm.pose.bones[name].rotation_quaternion = Euler(angles, 'XYZ').to_quaternion()


def apply_pose(arm, pose, offsets):
    """Root + FK, then the four analytic legs."""
    import bpy
    reset_pose(arm)
    arm.pose.bones["root"].location = pose["root"]
    set_fk(arm, pose["fk"])
    bpy.context.view_layer.update()
    if "targets" in pose:
        for leg in LEGS:
            solve_leg(arm, leg, pose["targets"][leg["key"]], pose.get("paw", {}).get(leg["key"], 0.0))
        return
    gait, base = pose["gait"], pose["phase"]
    for leg in LEGS:
        phase = base + gait["offset"][leg["key"]]
        y, z = foot_path(leg["front"], phase, gait, offsets[leg["key"]])
        solve_leg(arm, leg, (leg["side"] * LEG_X[leg["front"]], y, z), paw_angle_for(leg, phase, gait))


def frame_pose(arm, body, clip, frame, offsets, sit):
    """Pose one frame and return nothing; the caller keys it."""
    t = frame / FPS
    if clip == "idle":
        pose = idle_pose(t, 0.0)
        pose["targets"] = {leg["key"]: (leg["side"] * LEG_X[leg["front"]], REST_DISTAL[leg["front"]][0],
                                        REST_DISTAL[leg["front"]][1] + offsets[leg["key"]]) for leg in LEGS}
        apply_pose(arm, pose, offsets)
    elif clip == "sit":
        pose = sit
        breath = math.sin(math.tau * 1.5 * t)
        fk = dict(pose["fk"])
        fk["spine_02"] = (0.008 * breath, 0.0, 0.0)
        fk["spine_03"] = (0.006 * breath, 0.0, 0.0)
        fk["neck"] = (pose["fk"]["neck"][0] - 0.010 * breath, 0.0, 0.0)
        fk["head"] = (pose["fk"]["head"][0] + 0.008 * breath, 0.0, math.radians(6.0) * math.sin(math.tau * t / 4.0))
        pose = dict(pose, fk=fk)
        apply_pose(arm, pose, offsets)
    else:
        apply_pose(arm, locomotion_pose(clip, t, 0.0), offsets)


def key_pose(arm, frame):
    for bone in arm.pose.bones:
        bone.keyframe_insert("location", frame=frame, group=bone.name)
        bone.keyframe_insert("rotation_quaternion", frame=frame, group=bone.name)


def bake_clip(arm, body, clip, offsets, sit):
    import bpy
    frames = list(range(0, CLIPS[clip]["frames"] + 1, CLIPS[clip]["sample"]))
    action = bpy.data.actions.new(clip)
    action.use_fake_user = True
    if arm.animation_data is None:
        arm.animation_data_create()
    arm.animation_data.action = action
    for frame in frames:
        bpy.context.scene.frame_set(frame)
        frame_pose(arm, body, clip, frame, offsets, sit)
        key_pose(arm, frame)
    for fcurve in action_fcurves(action):
        for key in fcurve.keyframe_points:
            key.interpolation = 'LINEAR'
    return action


def action_fcurves(action):
    """F-curves of a (possibly slotted) action; Blender 5 keeps them in the channelbag."""
    curves = list(getattr(action, "fcurves", []) or [])
    if curves:
        return curves
    for layer in action.layers:
        for strip in layer.strips:
            for slot in action.slots:
                try:
                    curves.extend(strip.channelbag(slot).fcurves)
                except (AttributeError, TypeError):
                    continue
    return curves


