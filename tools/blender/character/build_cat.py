def bone_table(dz):
    """24 bones: root, 3 spine, neck, head, 2 ears, 4 tail, 3 per leg."""
    z = lambda h: h + dz
    bones = [
        # name, head, tail, parent, connected, deform
        ("root", (0, 0, z(0.02)), (0, 0.08, z(0.02)), None, False, False),
        ("spine_01", (0, -0.16, z(0.20)), (0, -0.06, z(0.205)), "root", False, True),
        ("spine_02", (0, -0.06, z(0.205)), (0, 0.04, z(0.195)), "spine_01", True, True),
        ("spine_03", (0, 0.04, z(0.195)), (0, 0.10, z(0.20)), "spine_02", True, True),
        ("neck", (0, 0.11, z(0.215)), (0, 0.19, z(0.245)), "spine_03", False, True),
        ("head", (0, 0.19, z(0.245)), (0, 0.265, z(0.255)), "neck", True, True),
        ("ear_L", (-0.020, 0.213, z(0.278)), (-0.032, 0.218, z(0.310)), "head", False, True),
        ("ear_R", (0.020, 0.213, z(0.278)), (0.032, 0.218, z(0.310)), "head", False, True),
        ("tail_01", (0, -0.205, z(0.195)), (0, -0.280, z(0.165)), "spine_01", False, True),
        ("tail_02", (0, -0.280, z(0.165)), (0, -0.350, z(0.125)), "tail_01", True, True),
        ("tail_03", (0, -0.350, z(0.125)), (0, -0.410, z(0.100)), "tail_02", True, True),
        ("tail_04", (0, -0.410, z(0.100)), (0, -0.465, z(0.100)), "tail_03", True, True),
    ]
    for leg in LEGS:
        s, front = leg["side"], leg["front"]
        x = s * LEG_X[front]
        if front:
            upper = (x, 0.100, z(0.155)); knee = (x, 0.108, z(0.078)); ankle = (x, REST_Y[True], z(ANKLE_Z[True]))
        else:
            upper = (x, -0.145, z(0.170)); knee = (x, -0.175, z(0.085)); ankle = (x, -0.200, z(ANKLE_Z[False]))
        paw_tip = (ankle[0], ankle[1] + 0.030, ankle[2])  # paw bone points forward, held level
        parent = "spine_03" if front else "spine_01"
        prefix = "foreleg" if front else "hindleg"
        suffix = "L" if s < 0 else "R"
        bones += [
            (f"{prefix}_upper_{suffix}", upper, knee, parent, False, True),
            (f"{prefix}_lower_{suffix}", knee, ankle, f"{prefix}_upper_{suffix}", True, True),
            (f"{PAW_GROUP[front]}_{suffix}", ankle, paw_tip, f"{prefix}_lower_{suffix}", True, True),
        ]
    return bones


def build_armature(dz):
    import bpy
    data = bpy.data.armatures.new("ARM_cat")
    arm = bpy.data.objects.new("ARM_cat", data)
    bpy.context.scene.collection.objects.link(arm)
    bpy.context.view_layer.objects.active = arm
    arm.select_set(True)
    bpy.ops.object.mode_set(mode='EDIT')
    for name, head, tail, parent, connected, deform in bone_table(dz):
        eb = data.edit_bones.new(name)
        eb.head, eb.tail, eb.roll = head, tail, 0.0
        eb.use_deform = deform
        if parent:
            eb.parent = data.edit_bones[parent]
            eb.use_connect = connected
    bpy.ops.object.mode_set(mode='OBJECT')
    if len(data.bones) != 24:
        fail(f"armature has {len(data.bones)} bones, expected 24")
    return arm


def bone_names():
    return [row[0] for row in bone_table(0.0)]


