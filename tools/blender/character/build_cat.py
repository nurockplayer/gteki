def point_segment_distance(point, head, tail):
    segment = tail - head
    length2 = segment.length_squared
    t = 0.0 if length2 == 0.0 else max(0.0, min(1.0, (point - head).dot(segment) / length2))
    return (point - (head + segment * t)).length


def skin_candidate(name, co):
    """Region rules: which bones may deform a body vertex at `co`."""
    x, y, z = co
    if name.startswith("ear"):
        return False  # ears live on the shells only
    if name.startswith(("foreleg", "forepaw", "hindleg", "hindpaw")):
        if abs(x) <= 0.008:
            return False
        if name.rsplit("_", 1)[1] != ("L" if x < 0 else "R"):
            return False
        if name.startswith("hind") and not (y < -0.06):
            return False
        if name.startswith("fore") and not (0.055 < y < 0.15):
            return False
        return True
    if name.startswith("tail"):
        return y < -0.185
    if name == "head" and y < 0.13:
        return False
    return True


def leg_falloff(name, co):
    """A leg bone fades out over a 2.5 cm band above its joint, so the body above it stays put."""
    if not name.startswith(("foreleg", "forepaw", "hindleg", "hindpaw")):
        return 1.0
    joint = 0.165 if name.startswith(("foreleg", "forepaw")) else 0.15
    return clamp01((joint + 0.025 - co.z) / 0.05)


def skin_body(body, arm):
    """Distance skinning: w = 1 / max(d, 4 mm)^4 over the region's bones, top 3, normalised.

    `smooth_weights` then relaxes the seams and keeps the strongest four.
    """
    from mathutils import Vector
    bones = [(b.name, b.head_local.copy(), b.tail_local.copy()) for b in arm.data.bones if b.use_deform]
    groups = {}
    for name, _head, _tail in bones:
        groups[name] = body.vertex_groups.new(name=name) if name not in body.vertex_groups else body.vertex_groups[name]
    for vertex in body.data.vertices:
        co = vertex.co
        scored = []
        for name, head, tail in bones:
            if not skin_candidate(name, co):
                continue
            falloff = leg_falloff(name, co)
            if falloff <= 0.0:
                continue
            scored.append((point_segment_distance(co, head, tail) / max(falloff, 1e-3) ** 0.25, name))
        scored.sort()
        chosen = scored[:3]
        weights = [(name, 1.0 / max(d, 0.004) ** 4) for d, name in chosen]
        total = sum(w for _name, w in weights)
        for name, weight in weights:
            groups[name].add([vertex.index], weight / total, 'REPLACE')


def rigid_paws(body, arm):
    """The toe half of each paw is rigid to its bone: the floor contact is then the bone's own.

    Only the distal half is forced; the pastern keeps its distance weights, so the hock and the
    wrist bend instead of tearing open at a hard seam. Returns the forced vertex indices.
    """
    rigid = set()
    index = {g.name: g.index for g in body.vertex_groups}
    names = {name: index[name] for name in index if name.startswith(("forepaw_", "hindpaw_"))}
    bones = {b.name: (b.head_local.copy(), b.tail_local.copy()) for b in arm.data.bones if b.name in names}
    for vertex in body.data.vertices:
        primary = max(vertex.groups, key=lambda g: g.weight, default=None)
        if primary is None:
            continue
        for name, group_index in names.items():
            if primary.group != group_index:
                continue
            head, tail = bones[name]
            segment = tail - head
            t = (vertex.co - head).dot(segment) / segment.length_squared
            if t < 0.45:
                break
            group = body.vertex_groups[name]
            for other in body.vertex_groups:
                if other != group:
                    other.remove([vertex.index])
            group.add([vertex.index], 1.0, 'REPLACE')
            rigid.add(vertex.index)
            break
    return rigid


def smooth_weights(body, rigid, iterations=3, keep=4, factor=0.5):
    """Relax the distance seams with 1-ring averaging, then keep the strongest `keep` and normalise."""
    groups = list(body.vertex_groups)
    neighbours = [[] for _ in body.data.vertices]
    for edge in body.data.edges:
        a, b = edge.vertices
        neighbours[a].append(b)
        neighbours[b].append(a)
    weights = [{groups[g.group].name: g.weight for g in vertex.groups if g.weight > 0.0}
               for vertex in body.data.vertices]
    for _ in range(iterations):
        relaxed = []
        for i, row in enumerate(weights):
            ring = neighbours[i]
            if i in rigid or not ring:
                relaxed.append(row)
                continue
            around = {}
            for j in ring:
                for name, weight in weights[j].items():
                    around[name] = around.get(name, 0.0) + weight
            relaxed.append({name: (1.0 - factor) * row.get(name, 0.0) + factor * around.get(name, 0.0) / len(ring)
                            for name in set(row) | set(around)})
        weights = relaxed
    for i, vertex in enumerate(body.data.vertices):
        best = sorted(weights[i].items(), key=lambda item: -item[1])[:keep]
        total = sum(weight for _name, weight in best) or 1.0
        for group in groups:
            group.remove([vertex.index])
        for name, weight in best:
            body.vertex_groups[name].add([vertex.index], weight / total, 'REPLACE')


