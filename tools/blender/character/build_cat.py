def srgb_to_linear(hex_string):
    hex_string = hex_string.lstrip("#")
    out = []
    for i in (0, 2, 4):
        c = int(hex_string[i:i + 2], 16) / 255.0
        out.append(c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4)
    return tuple(out)


BACK_L, FLANK_L, BELLY_L = srgb_to_linear(BACK), srgb_to_linear(FLANK), srgb_to_linear(BELLY)
INNER_EAR_L, NOSE_L, EYE_L, PUPIL_L, STRIPE_L = (srgb_to_linear(c) for c in (INNER_EAR, NOSE, EYE, PUPIL, STRIPE))


def clamp01(x):
    return 0.0 if x < 0.0 else 1.0 if x > 1.0 else x


def smoothstep(a, b, x):
    t = clamp01((x - a) / (b - a))
    return t * t * (3.0 - 2.0 * t)


def mix(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


def bar(u, period):
    """Soft stripe profile in [0, 1]."""
    return (0.5 + 0.5 * math.cos((u / period) * math.tau)) ** 6


def body_colour(co, tabby):
    """Back/flank/belly gradient by surface height and side, plus optional mackerel stripes."""
    x, y, z = co
    t = clamp01((z - 0.055) / 0.185)
    t = clamp01(t - 0.10 * clamp01(abs(x) / 0.055))
    colour = mix(BELLY_L, FLANK_L, smoothstep(0.0, 0.5, t)) if t < 0.5 else mix(FLANK_L, BACK_L, smoothstep(0.5, 1.0, t))
    if tabby:
        if y < -0.24:                                   # tail rings
            strength = 0.55 * bar(-y, 0.045)
        elif z < 0.16 and abs(x) > 0.018:               # leg rings
            strength = 0.50 * bar(z, 0.040)
        else:                                           # mackerel bars across the back
            strength = 0.60 * bar(y, 0.062) * smoothstep(0.35, 0.70, t)
        colour = mix(colour, STRIPE_L, strength)
    return colour


